// =========================================================
// GET CURRENT LANGUAGE
// =========================================================

function getCurrentLanguage() {

    return (
        localStorage.getItem(
            "yzVoiceLanguage"
        ) || "zh-CN"
    );

}



// =========================================================
// TRANSLATE KEY
// =========================================================

function t(key) {

    const language =
        getCurrentLanguage();


    const dictionary =
        translations[
            language
        ];


    if (
        dictionary &&
        dictionary[key] !== undefined
    ) {

        return dictionary[key];

    }


    // 找不到翻译时直接返回 key
    // 方便我们调试

    return key;

}



// =========================================================
// SET LANGUAGE
// =========================================================

function setLanguage(language) {

    if (
        !translations[
            language
        ]
    ) {

        return;

    }


    localStorage.setItem(
        "yzVoiceLanguage",
        language
    );


    document.documentElement.lang =
        language;


    applyLanguage();


    // =========================
    // 首页房间卡片重新生成
    // =========================

    if (
        typeof generateRooms ===
        "function"
    ) {

        let category =
            "all";


        const activeButton =
            document.querySelector(
                ".room-filter .filter-btn.active"
            );


        if (activeButton) {

            category =
                activeButton.getAttribute(
                    "data-category"
                ) || "all";

        }


        generateRooms(
            category
        );

    }


    // =========================
    // 房间页面重新绘制麦位
    // =========================

    if (
        typeof renderAllSeats ===
        "function"
    ) {

        renderAllSeats();

    }


    // =========================
    // 房间在线人数
    // =========================

    if (
        typeof updateRoomOnlineText ===
        "function"
    ) {

        updateRoomOnlineText();

    }

}



// =========================================================
// APPLY LANGUAGE TO HTML
// =========================================================

function applyLanguage() {

    const language =
        getCurrentLanguage();


    const dictionary =
        translations[
            language
        ];


    if (!dictionary) {

        return;

    }


    document.documentElement.lang =
        language;



    // =====================================================
    // NORMAL TEXT
    // =====================================================

    document
        .querySelectorAll(
            "[data-i18n]"
        )
        .forEach(
            function(element) {

                const key =
                    element.getAttribute(
                        "data-i18n"
                    );


                if (
                    dictionary[
                        key
                    ] !== undefined
                ) {

                    element.innerText =
                        dictionary[
                            key
                        ];

                }

            }
        );



    // =====================================================
    // PLACEHOLDER
    // =====================================================

    document
        .querySelectorAll(
            "[data-i18n-placeholder]"
        )
        .forEach(
            function(element) {

                const key =
                    element.getAttribute(
                        "data-i18n-placeholder"
                    );


                if (
                    dictionary[
                        key
                    ] !== undefined
                ) {

                    element.placeholder =
                        dictionary[
                            key
                        ];

                }

            }
        );



    // =====================================================
    // LANGUAGE SELECTOR
    // =====================================================

    const selector =
        document.getElementById(
            "language-selector"
        );


    if (selector) {

        selector.value =
            language;

    }



    // =====================================================
    // EMPTY SEAT NAMES
    // 只修改空麦
    // 有用户在麦上的话不要覆盖用户名
    // =====================================================

    for (
        let seatNumber = 1;
        seatNumber <= 8;
        seatNumber++
    ) {

        const seat =
            document.querySelector(
                '[data-seat="' +
                seatNumber +
                '"]'
            );


        const seatName =
            document.getElementById(
                "seat-name-" +
                seatNumber
            );


        if (
            seat &&
            seatName &&
            seat.classList.contains(
                "empty-seat"
            )
        ) {

            seatName.innerText =
                t(
                    "seat" +
                    seatNumber
                );

        }

    }



    // =====================================================
    // MICROPHONE BUTTON CURRENT STATUS
    // =====================================================

    const micText =
        document.getElementById(
            "mic-text"
        );


    if (
        micText &&
        typeof microphoneEnabled !==
            "undefined"
    ) {

        if (microphoneEnabled) {

            micText.innerText =
                t(
                    "microphoneOn"
                );

        }

        else {

            micText.innerText =
                t(
                    "microphone"
                );

        }

    }

}



// =========================================================
// HELPER
// 获取空麦文字
// =========================================================

function getSeatText(
    seatNumber
) {

    return t(
        "seat" +
        seatNumber
    );

}



// =========================================================
// HELPER
// 获取在线人数文字
// =========================================================

function getOnlineText(
    number
) {

    return (
        "👥 " +
        number +
        " " +
        t("online")
    );

}



// =========================================================
// PAGE LOAD
// =========================================================

document.addEventListener(
    "DOMContentLoaded",
    function() {

        applyLanguage();

    }
);



