// =========================================================
// GET CURRENT LANGUAGE
// =========================================================

function getCurrentLanguage() {

    return (
        localStorage.getItem(
            "yzVoiceLanguage"
        ) ||
        "zh-CN"
    );

}



// =========================================================
// TRANSLATE KEY
// =========================================================

function t(key) {

    const language =
        getCurrentLanguage();


    const dictionary =
        translations[
            language
        ];


    if (
        dictionary &&
        dictionary[key] !== undefined
    ) {

        return dictionary[key];

    }


    // 找不到翻译时返回 key，
    // 方便查看哪里漏了翻译

    return key;

}



// =========================================================
// SET LANGUAGE
// =========================================================

function setLanguage(language) {

    if (
        !translations[
            language
        ]
    ) {

        return;

    }


    localStorage.setItem(
        "yzVoiceLanguage",
        language
    );


    document.documentElement.lang =
        language;


    applyLanguage();



    // =====================================================
    // 首页房间卡片重新生成
    // =====================================================

    if (
        typeof window.generateRooms ===
        "function"
    ) {

        let category =
            "all";


        const activeButton =
            document.querySelector(
                ".room-filter .filter-btn.active"
            );


        if (activeButton) {

            category =
                activeButton.getAttribute(
                    "data-category"
                ) ||
                "all";

        }


        window.generateRooms(
            category
        );

    }



    // =====================================================
    // 房间麦位重新绘制
    // =====================================================

    if (
        typeof window.renderAllSeats ===
        "function"
    ) {

        window.renderAllSeats();

    }



    // =====================================================
    // 房间在线人数刷新
    // =====================================================

    if (
        typeof window.updateRoomOnlineText ===
        "function"
    ) {

        window.updateRoomOnlineText();

    }

}



// =========================================================
// APPLY LANGUAGE
// =========================================================

function applyLanguage() {

    const language =
        getCurrentLanguage();


    const dictionary =
        translations[
            language
        ];


    if (!dictionary) {

        return;

    }


    document.documentElement.lang =
        language;



    // =====================================================
    // NORMAL TEXT
    // data-i18n="..."
    // =====================================================

    document
        .querySelectorAll(
            "[data-i18n]"
        )
        .forEach(
            function(element) {

                const key =
                    element.getAttribute(
                        "data-i18n"
                    );


                if (
                    dictionary[key] !==
                    undefined
                ) {

                    element.textContent =
                        dictionary[key];

                }

            }
        );



    // =====================================================
    // PLACEHOLDER
    // data-i18n-placeholder="..."
    // =====================================================

    document
        .querySelectorAll(
            "[data-i18n-placeholder]"
        )
        .forEach(
            function(element) {

                const key =
                    element.getAttribute(
                        "data-i18n-placeholder"
                    );


                if (
                    dictionary[key] !==
                    undefined
                ) {

                    element.placeholder =
                        dictionary[key];

                }

            }
        );



    // =====================================================
    // TITLE
    // data-i18n-title="..."
    // =====================================================

    document
        .querySelectorAll(
            "[data-i18n-title]"
        )
        .forEach(
            function(element) {

                const key =
                    element.getAttribute(
                        "data-i18n-title"
                    );


                if (
                    dictionary[key] !==
                    undefined
                ) {

                    element.title =
                        dictionary[key];

                }

            }
        );



    // =====================================================
    // LANGUAGE SELECTOR
    // =====================================================

    const selector =
        document.getElementById(
            "language-selector"
        );


    if (selector) {

        selector.value =
            language;

    }



    // =====================================================
    // EMPTY SEAT NAMES
    // 有人在麦位时不覆盖用户名
    // =====================================================

    for (
        let seatNumber = 1;
        seatNumber <= 8;
        seatNumber++
    ) {

        const seat =
            document.querySelector(
                `[data-seat="${seatNumber}"]`
            );


        const seatName =
            document.getElementById(
                "seat-name-" +
                seatNumber
            );


        if (
            seat &&
            seatName &&
            seat.classList.contains(
                "empty-seat"
            )
        ) {

            seatName.textContent =
                t(
                    "seat" +
                    seatNumber
                );

        }

    }



    // =====================================================
    // MICROPHONE CURRENT TEXT
    // =====================================================

    const micText =
        document.getElementById(
            "mic-text"
        );


    if (
        micText &&
        typeof window.microphoneEnabled !==
        "undefined"
    ) {

        if (
            window.microphoneEnabled
        ) {

            micText.textContent =
                t(
                    "microphoneOn"
                );

        }

        else {

            micText.textContent =
                t(
                    "microphone"
                );

        }

    }

}



// =========================================================
// GET SEAT TEXT
// =========================================================

function getSeatText(
    seatNumber
) {

    return t(
        "seat" +
        seatNumber
    );

}



// =========================================================
// GET ONLINE TEXT
// =========================================================

function getOnlineText(
    number
) {

    return (
        "👥 " +
        number +
        " " +
        t(
            "online"
        )
    );

}



